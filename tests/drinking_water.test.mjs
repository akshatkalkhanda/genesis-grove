test('well construction targets an underserved remote colony and its residents retain saved homes', () => {
    const { world, kingdom } = setup();
    kingdom.houses = [{ x: 48, y: 48 }];
    const colony = world.found_colony(kingdom.id, 128, 48);
    assert.ok(colony);
    for (let i = 0; i < 5; i++) {
        world.add_person(48, 48, kingdom.id);
        world.people.at(-1).home_id = kingdom.id;
        world.add_person(128, 48, kingdom.id);
        world.people.at(-1).home_id = colony.id;
    }
    kingdom.food = 200; kingdom.wood = 4;
    kingdom.buildings = [
        { type: 'well', x: 48, y: 48, growth: 0, harvests: 0, water_stock: 10 },
        { type: 'farm', x: 44, y: 48, growth: 0, harvests: 0 },
        { type: 'clinic', x: 48, y: 44, growth: 0, harvests: 0 },
        { type: 'granary', x: 52, y: 48, growth: 0, harvests: 0 }
    ];
    const plan = well_construction(world, kingdom);
    assert.ok(plan.limit >= 2);
    assert.equal(plan.origin.id, colony.id);
    assert.equal(plan.unserved, true);
    assert.equal(water_access(world, colony), false, 'a distant capital well does not count as colony access');

    advance_buildings(world, kingdom, 12, 10, 0);
    const new_wells = kingdom.buildings.filter(b => b.type === 'well' && Math.hypot(b.x - 48, b.y - 48) > 32);
    assert.equal(new_wells.length, 1, 'the second finite well is built near the underserved colony');
    assert.ok(Math.hypot(new_wells[0].x - colony.x, new_wells[0].y - colony.y) <= 12);
    assert.equal(water_access(world, colony), true);
    const restored = World.deserialize(world.serialize());
    assert.ok(restored.people.filter(p => p.home_id === colony.id).length >= 5,
        'colony home assignments remain valid after a save round trip');
    assert.equal(water_access(restored, restored.colonies.find(c => c.id === colony.id)), true);
});

