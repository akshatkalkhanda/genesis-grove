function setup() {
    const world = new World({ preset: 'empty', inhabited: false, seed: 'finite-drinking-water' });
    world.tiles.fill(T.GRASS);
    const kingdom = world.found_village(48, 48);
    world.add_person(48, 48, kingdom.id);
    const person = world.people[0];
    person.health = 100;
    initialize_water(person);
    return { world, kingdom, person };
}

function add_well(kingdom, stock = WATER.well_initial, x = kingdom.x, y = kingdom.y) {
    const building = { type: 'well', x, y, growth: 0, harvests: 0, water_stock: stock };
    kingdom.buildings.push(building);
    return building;
}

function pond(world, x = 40, y = 40, width = 4, height = 4) {
    for (let dy = 0; dy < height; dy++) for (let dx = 0; dx < width; dx++) {
        world.set_tile(x + dx, y + dy, T.OCEAN);
    }
}

test('wells provide finite rations and bottle capacity carries only water already withdrawn', () => {
    const { world, kingdom, person } = setup();
    const well = add_well(kingdom, 3);
    initialize_water_world(world);
    person.needs.hydration = 0;
    assert.equal(water_intent(world, person).action, 'Drinking');
    assert.equal(person.needs.hydration, WATER.drink_nutrition);
    assert.equal(person.water_carried, 1);
    assert.equal(well.water_stock, 1);
    assert.equal(water_intent(world, person).action, 'Drinking');
    assert.equal(person.water_carried, 0);
    assert.equal(well.water_stock, 1, 'drinking a carried ration does not debit the source twice');
    person.needs.hydration = 0;
    water_intent(world, person);
    assert.equal(person.needs.hydration, WATER.drink_nutrition);
    assert.equal(well.water_stock, 0);
    assert.equal(water_intent(world, person).action, 'Waiting for water');
    assert.equal(well.water_stock, 0, 'depleted water cannot be generated by thirst decisions');
});

test('a thirsty person at a well site corner drinks from that same tile instead of seeking a distant source', () => {
    const { world, kingdom, person } = setup();
    const well = add_well(kingdom, 3, 48, 48);
    person.x = 48.9; person.y = 48.9;
    person.needs.hydration = 0;
    initialize_water_world(world);
    const intent = water_intent(world, person);
    assert.equal(intent.action, 'Drinking');
    assert.equal(person.needs.hydration, WATER.drink_nutrition);
    assert.equal(person.water_carried, 1);
    assert.equal(well.water_stock, 1, 'the real well supplies a drink and one finite carried ration');
});

test('hydration drives real walking and a World step withdraws source water before restoring it', () => {
    const { world, kingdom, person } = setup();
    const well = add_well(kingdom, WATER.well_capacity, 56, 48);
    initialize_water_world(world);
    person.needs.hydration = WATER.thirsty - 1;
    person.needs.nutrition = 100; person.needs.energy = 100; person.needs.decision_timer = 0;
    const original_stock = well.water_stock;
    const original_position = { x: person.x, y: person.y };
    const midjourney = World.deserialize(world.serialize());
    for (let step = 0; step < 200; step++) {
        world.step(0.125);
        midjourney.step(0.125);
        assert.deepEqual(midjourney.serialize(), world.serialize(), 'water route is deterministic across a save');
        if (well.water_stock < original_stock) break;
    }
    assert.ok(person.x > original_position.x + 1, 'the resident walks to the distant well');
    assert.ok(well.water_stock < original_stock, 'a completed drink withdraws finite well stock');
    assert.ok(person.needs.hydration > WATER.thirsty, 'hydration rises after the real source visit');
    assert.ok(world.effects.some(effect => effect.type === 'drink'));
});

test('danger precedes critical thirst, which precedes hunger, ordinary thirst, and resting', () => {
    const { world, kingdom, person } = setup();
    const enemy = world.found_village(52, 48);
    world.add_person(50, 48, enemy.id);
    const soldier = world.people.at(-1); soldier.role = 'soldier';
    world.set_relation(kingdom.id, enemy.id, 'war');
    person.needs.hydration = 0; person.needs.nutrition = 100; person.needs.energy = 10;
    person.needs.decision_timer = 0;
    assert.equal(needs_intent(world, person, 0.125, decision_context(world), kingdom)?.action,
        'Escaping danger');

    person.needs.intent = null; person.needs.decision_timer = 0;
    world.set_relation(kingdom.id, enemy.id, 'peace');
    assert.equal(needs_intent(world, person, 0.125, decision_context(world), kingdom)?.action,
        'Seeking water');

    person.needs.hydration = 50; person.needs.nutrition = 10; person.needs.energy = 100;
    person.needs.intent = null; person.needs.decision_timer = 0;
    assert.equal(needs_intent(world, person, 0.125, decision_context(world), kingdom)?.action,
        'Eating');

    person.needs.hydration = 50; person.needs.nutrition = 100; person.needs.energy = 5;
    person.needs.intent = null; person.needs.decision_timer = 0;
    assert.equal(needs_intent(world, person, 0.125, decision_context(world), kingdom)?.action,
        'Seeking water');
});

