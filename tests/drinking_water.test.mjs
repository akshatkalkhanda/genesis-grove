test('legacy hydration and source records are bounded, and malformed reservoirs are rejected', () => {
    const { world, kingdom, person } = setup();
    const well = add_well(kingdom);
    initialize_water_world(world);
    const save = world.serialize();
    for (const value of [-1, 101, Infinity, NaN]) {
        const bad = structuredClone(save); bad.people[0].needs.hydration = value;
        assert.throws(() => World.deserialize(bad));
    }
    for (const value of [-1, WATER.well_capacity + 1, Infinity]) {
        const bad = structuredClone(save); bad.villages[0].buildings[0].water_stock = value;
        assert.throws(() => World.deserialize(bad));
    }
    for (const value of [-1, WATER.carry_capacity + 1, 0.5, Infinity]) {
        const bad = structuredClone(save); bad.people[0].water_carried = value;
        assert.throws(() => World.deserialize(bad));
    }
    for (const bad_sources of [
        [{ anchor: -1, stock: 0 }], [{ anchor: WIDTH * HEIGHT, stock: 0 }],
        [{ anchor: 0, stock: -1 }], [{ anchor: 0, stock: Infinity }],
        [{ anchor: 0, stock: WATER.lake_capacity + 1 }],
        [{ anchor: 0, stock: 1 }, { anchor: 0, stock: 2 }]
    ]) {
        assert.equal(valid_water({ ...save, water_sources: bad_sources }, WIDTH * HEIGHT), false);
    }
    const legacy = structuredClone(save);
    delete legacy.water_sources;
    delete legacy.people[0].needs.hydration; delete legacy.people[0].water_carried;
    delete legacy.villages[0].buildings[0].water_stock;
    const restored = World.deserialize(legacy);
    assert.equal(restored.people[0].needs.hydration, WATER.initial_hydration);
    assert.equal(restored.people[0].water_carried, 0);
    assert.equal(restored.villages[0].buildings[0].water_stock, WATER.well_initial);
    assert.ok(well);
});
