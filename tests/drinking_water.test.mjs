test('a founding voyage carries its paid well kit to a colony and constructs a local well exactly once', () => {
    const { world, kingdom } = setup();
    for (let i = 0; i < 2; i++) world.add_person(48, 48, kingdom.id);
    kingdom.food = 10; kingdom.wood = 6;
    const original_wood = kingdom.wood;
    assert.equal(world.launch_colony(kingdom.id, 80, 48), true);
    assert.equal(kingdom.wood, original_wood - 6, 'the kit comes from the existing founding timber cost');
    assert.equal(kingdom.food, 0);
    assert.equal(world.voyages[0].well_kit, WATER.well_build_wood);
    const voyage_save = world.serialize();
    const resumed = World.deserialize(voyage_save);
    assert.equal(resumed.voyages[0].well_kit, WATER.well_build_wood);
    const invalid_kit = structuredClone(voyage_save);
    invalid_kit.voyages[0].well_kit = WATER.well_build_wood + 1;
    assert.throws(() => World.deserialize(invalid_kit));
    const legacy_voyage = structuredClone(voyage_save);
    delete legacy_voyage.water_sources;
    delete legacy_voyage.voyages[0].well_kit;
    assert.equal(World.deserialize(legacy_voyage).voyages[0].well_kit, WATER.well_build_wood,
        'older active voyages receive one bounded kit during migration');

    const duration = resumed.voyages[0].duration;
    resumed.advance_voyages(duration);
    const colony = resumed.colonies.find(c => c.kingdom_id === kingdom.id);
    assert.ok(colony);
    assert.equal(colony.well_kit, WATER.well_build_wood);
    assert.equal(resumed.villages[0].wood, 0);
    const saved_home_ids = resumed.people.map(p => p.home_id);
    advance_buildings(resumed, resumed.villages[0], 12, 3, 0);
    const wells_after_build = resumed.villages[0].buildings.filter(b => b.type === 'well');
    assert.equal(wells_after_build.length, 1);
    assert.ok(Math.hypot(wells_after_build[0].x - colony.x, wells_after_build[0].y - colony.y) <= 12);
    assert.equal(colony.well_kit, 0);
    assert.equal(resumed.villages[0].wood, 0, 'construction consumes the prepaid kit without shared-wood credit');
    assert.equal(water_access(resumed, colony), true);
    advance_buildings(resumed, resumed.villages[0], 12, 3, 0);
    assert.equal(resumed.villages[0].buildings.filter(b => b.type === 'well').length, 1,
        'the consumed kit cannot construct a duplicate well');
    assert.deepEqual(resumed.people.map(p => p.home_id), saved_home_ids);
    assert.equal(World.deserialize(resumed.serialize()).colonies.find(c => c.id === colony.id).well_kit, 0);
});

test('only enclosed ponds of four or more tiles become fresh sources, never open sea', () => {
    const { world, person } = setup();
    pond(world, 50, 40, 2, 2);
    pond(world, 70, 40, 2, 2);
    for (let y = 0; y < HEIGHT; y++) world.set_tile(70, y, T.OCEAN);
    invalidate_water(world);
    initialize_water_world(world, true);
    assert.equal(world.water_sources.length, 1);
    assert.equal(water_topology(world).length, 1);
    assert.equal(water_topology(world)[0].area, 4);
    assert.equal(world.water_sources[0].stock, 4 * WATER.lake_per_tile);

    for (let y = 0; y < HEIGHT; y++) for (let x = 0; x < 8; x++) world.set_tile(x, y, T.OCEAN);
    invalidate_water(world); initialize_water_world(world);
    assert.equal(world.water_sources.length, 1, 'edge-connected sea does not become an extra source');
    for (let y = 40; y < 42; y++) for (let x = 50; x < 52; x++) world.set_tile(x, y, T.GRASS);
    invalidate_water(world); initialize_water_world(world);
    assert.equal(world.water_sources.length, 0);
    person.x = 3; person.y = 40;
    assert.equal(water_access(world, person), false);
    assert.equal(water_intent(world, person).action, 'Seeking water');
});

