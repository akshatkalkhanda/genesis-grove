test('pond split and merge conserve stock without refilling a new component', () => {
    const { world } = setup();
    pond(world, 40, 40, 8, 4);
    initialize_water_world(world, true);
    assert.equal(world.water_sources.length, 1);
    world.water_sources[0].stock = 37;
    for (let y = 40; y < 44; y++) world.set_tile(44, y, T.GRASS);
    initialize_water_world(world);
    assert.equal(world.water_sources.length, 2);
    const [left, right] = world.water_sources;
    assert.equal(left.anchor, world.index(40, 40));
    assert.equal(left.stock, 37);
    assert.equal(right.anchor, world.index(45, 40));
    assert.equal(right.stock, 0);
    for (let y = 40; y < 44; y++) world.set_tile(44, y, T.OCEAN);
    initialize_water_world(world);
    assert.equal(world.water_sources.length, 1);
    assert.equal(world.water_sources[0].stock, 37);
});

