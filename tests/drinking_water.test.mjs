test('prisoners receive one finite ration only when a well is reachable from their prison', () => {
    const { world, kingdom, person } = setup();
    kingdom.buildings.push({ type: 'prison', x: 48, y: 48 },
        { type: 'well', x: 52, y: 48, water_stock: 2 });
    initialize_water_world(world);
    person.prisoner_of = kingdom.id;
    person.needs.hydration = 20;
    const well = kingdom.buildings.find(b => b.type === 'well');
    assert.equal(service_water(world, person, kingdom), true);
    assert.equal(person.needs.hydration, 20 + WATER.drink_nutrition);
    assert.equal(well.water_stock, 1, 'institutional service draws one ration without extra bottle refill');
    person.needs.hydration = 20;
    for (let y = 0; y < HEIGHT; y++) world.set_tile(50, y, T.MOUNTAIN);
    assert.equal(service_water(world, person, kingdom), false);
    assert.equal(person.needs.hydration, 20);
    assert.equal(well.water_stock, 1, 'a well behind a complete terrain barrier is not drawn remotely');
});

test('boat crew use carried water at sea and draw from a well only at their matching dock', () => {
    const { world, kingdom, person } = setup();
    const dock = { type: 'dock', x: 48, y: 48 };
    const aerodrome = { type: 'aerodrome', x: 48, y: 48 };
    const well = add_well(kingdom, 20, 52, 48);
    kingdom.buildings.push(aerodrome);
    initialize_water_world(world);
    const boat = { kind: 'boat', x: 60, y: 60, crew_aboard: true,
        crew_id: person.id, kingdom_id: kingdom.id };
    world._crew_assignments = new Map([[person.id, boat]]);
    world.set_tile(60, 60, T.OCEAN);
    person.water_carried = 1;
    person.needs.hydration = 20;
    assert.equal(service_water(world, person, kingdom), true);
    assert.equal(person.needs.hydration, 20 + WATER.drink_nutrition);
    assert.equal(person.water_carried, 0);
    assert.equal(well.water_stock, 20, 'the sea ration came from the saved bottle, not a remote well');
    person.needs.hydration = 20; person.water_carried = 0;
    assert.equal(service_water(world, person, kingdom), false, 'crew at sea cannot draw remote land water');
    assert.equal(well.water_stock, 20);

    boat.x = 48; boat.y = 48;
    assert.equal(service_water(world, person, kingdom), false, 'a boat cannot use an aerodrome in place of a dock');
    assert.equal(well.water_stock, 20);
    kingdom.buildings.push(dock);
    assert.equal(service_water(world, person, kingdom), true, 'the boat can replenish while at its own dock');
    assert.equal(person.needs.hydration, 20 + WATER.drink_nutrition);
    assert.equal(person.water_carried, 2);
    assert.equal(well.water_stock, 17, 'dock service debits one drink plus two finite carried rations');
});

test('drought slows well recharge, rain refills ponds, and invalid elapsed time has no effect', () => {
    const { world, kingdom } = setup();
    const well = add_well(kingdom, 20);
    pond(world, 40, 40, 2, 2);
    initialize_water_world(world, true);
    const pond_source = world.water_sources[0];
    pond_source.stock = 0;
    world.weather = [{ kind: 'drought', x: 48, y: 48, radius: 20 }];
    advance_water(world, 4);
    assert.equal(well.water_stock, 21);
    assert.ok(Math.abs(pond_source.stock - 0.08) < 1e-6,
        'drought slows pond groundwater while the well follows its own slower recharge');
    world.weather = [{ kind: 'raincloud', x: 41, y: 41, radius: 5 }];
    advance_water(world, 2);
    assert.ok(pond_source.stock > 2 && pond_source.stock < WATER.lake_capacity);
    const before = [well.water_stock, pond_source.stock];
    for (const dt of [0, -1, NaN]) advance_water(world, dt);
    assert.deepEqual([well.water_stock, pond_source.stock], before);
});

