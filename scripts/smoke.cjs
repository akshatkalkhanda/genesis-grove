const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
app.setPath('userData', path.join(app.getPath('temp'), `genesis-smoke-${process.pid}`));
app.whenReady().then(async () => {
    const errors = [], checks = [];
    const win = new BrowserWindow({ width: 1440, height: 940, show: false, webPreferences: { sandbox: true, nodeIntegration: false, contextIsolation: true } });
    win.webContents.on('console-message', details => { if (details.level === 'error') errors.push(details.message); });
    win.webContents.on('render-process-gone', (_event, details) => errors.push(`Renderer stopped: ${details.reason}`));
    const js = code => win.webContents.executeJavaScript(code, true);
    const click = async selector => {
        const rect = await js(`(()=>{const element=document.querySelector(${JSON.stringify(selector)});element.scrollIntoView({block:'center',inline:'nearest'});const r=element.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`);
        win.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(rect.x), y: Math.round(rect.y), button: 'left', clickCount: 1 });
        win.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(rect.x), y: Math.round(rect.y), button: 'left', clickCount: 1 });
        await delay(80);
    };
    try {
        const game_index = process.env.GENESIS_SMOKE_INDEX || path.join(__dirname, '..', 'index.html');
        await win.loadFile(game_index); await delay(750);
        const artifact_dir = path.join(__dirname, '..', 'artifacts'); await fs.mkdir(artifact_dir, { recursive: true });
        await fs.writeFile(path.join(artifact_dir, 'start-menu.png'), (await win.webContents.capturePage()).toPNG());
        assert.equal(await js('document.getElementById("start-screen").hidden'), false);
        assert.equal(await js('genesis.stats().villages'), 0);
        await click('#menu-create');
        await fs.writeFile(path.join(artifact_dir, 'world-setup.png'), (await win.webContents.capturePage()).toPNG());
        assert.equal(await js('document.getElementById("new-dialog").open'), true);
        assert.ok(await js('document.getElementById("preview-summary").textContent.includes("land")'));
        const old_seed = await js('document.querySelector("#new-form [name=seed]").value');
        await click('#regenerate-seed');
        assert.notEqual(await js('document.querySelector("#new-form [name=seed]").value'), old_seed);
        await js(`document.querySelector('#new-form [name=seed]').value='emerald-17';document.querySelector('#new-form [name=seed]').dispatchEvent(new Event('input'))`);
        await delay(150);
        const preview_land = Number((await js('document.getElementById("preview-summary").textContent')).split('%')[0]);
        await js(`document.querySelector('#new-form').requestSubmit()`);
        assert.equal(await js('genesis.snapshot().seed'), 'emerald-17');
        assert.equal(await js('genesis.stats().land'), preview_land);
        assert.equal(await js('document.getElementById("start-ready").hidden'), false);
        assert.equal(await js('document.getElementById("paused-banner").hidden'), false);
        await click('#menu-start');
        assert.equal(await js('document.getElementById("start-screen").hidden'), true);
        checks.push('Main menu previews and starts a chosen world');
        assert.equal(await js('window.genesis.stats().villages'), 3); checks.push('Initial populated world renders');
        assert.equal(await js('new Set(genesis.snapshot().villages.map(v => v.color)).size'), 3);
        assert.equal(await js('document.getElementById("age-label").textContent'), 'STONE AGE');
        assert.equal(await js('document.getElementById("soldiers").textContent'), '0');
        checks.push('Kingdom banners and Stone Age display are distinct');
        await click('#civilizations button');
        assert.equal(await js('document.getElementById("selected-kingdom").hidden'), false);
        assert.ok(await js('document.getElementById("selected-kingdom").textContent.includes("Supplies:")'));
        assert.ok(await js('document.getElementById("selected-kingdom").textContent.includes("Towns:")'));
        checks.push('Selecting a kingdom opens its detailed status panel');
        await click('#zoom-reset');
        assert.equal(await js('document.querySelectorAll("#tools button").length'), 16);
        await click('[data-category="life"]');
        assert.equal(await js('document.querySelectorAll("#tools button").length'), 12);
        await click('[data-category="creatures"]');
        assert.equal(await js('document.querySelectorAll("#tools button").length'), 18);
        await click('[data-category="terrain"]');
        checks.push('Biome, civilization, and wildlife catalogs expose the expanded choices');
        assert.equal(await js(`(()=>{const tabs=[...document.querySelectorAll('.tabs button')].map(e=>e.getBoundingClientRect());return tabs[0].right<=tabs[1].left&&tabs[0].bottom<=tabs[2].top})()`), true);
        checks.push('Tool categories fit without overlap');
        await fs.writeFile(path.join(artifact_dir, 'world-desktop.png'), (await win.webContents.capturePage()).toPNG());
        await click('#pause'); const before = await js('genesis.snapshot().time'); await delay(400);
        assert.equal(await js('genesis.snapshot().time'), before); checks.push('Pause freezes simulation');
        await click('[data-category="powers"]'); assert.equal(await js('document.querySelector("[data-tool=meteor]").textContent.includes("Meteor")'), true);
        await click('[data-tool="meteor"]');
        const target = await js(`(()=>{const w=genesis.snapshot(),i=w.tiles.findIndex((t,i)=>t===3&&i%192>60&&i%192<130&&Math.floor(i/192)>30&&Math.floor(i/192)<95),c=genesis.camera(),r=document.querySelector('#world').getBoundingClientRect();return {i,x:r.x+c.origin.x+(i%192)*6*c.base*c.zoom,y:r.y+c.origin.y+Math.floor(i/192)*6*c.base*c.zoom}})()`);
        assert.ok(target.i >= 0);
        win.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(target.x), y: Math.round(target.y), button: 'left', clickCount: 1 });
        win.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(target.x), y: Math.round(target.y), button: 'left', clickCount: 1 });
        await delay(100);
        assert.equal(await js(`genesis.snapshot().tiles[${target.i}]`), 7); checks.push('Native pointer input applies meteor to the map');
        await click('#zoom-in'); assert.ok(await js('genesis.camera().zoom > 1')); await click('#zoom-reset');
        assert.equal(await js('genesis.camera().zoom'), 1); checks.push('Zoom and fit controls work');
        await click('#save'); assert.ok(await js('localStorage.getItem("genesis-grove-world-v1") !== null')); checks.push('Device save persists world');
        await click('#new-world');
        await js(`document.querySelector('#new-form [name=name]').value='Smoke Ocean';document.querySelector('#new-form [name=seed]').value='';document.querySelector('#new-form [name=preset]').value='empty';document.querySelector('#new-form').requestSubmit()`);
        assert.equal(await js('genesis.snapshot().seed'), '');
        assert.equal(await js('genesis.stats().population'), 0); assert.equal(await js('genesis.stats().land'), 0);
        assert.equal(await js('document.getElementById("paused-banner").hidden'), false);
        await click('#menu-paint'); checks.push('New-world form creates paused empty ocean');
        await click('[data-category="terrain"]'); await click('[data-tool="grass"]');
        const middle = await js(`(()=>{const c=genesis.camera(),r=document.querySelector('#world').getBoundingClientRect();return{x:r.x+c.width/2,y:r.y+c.height/2}})()`);
        win.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(middle.x), y: Math.round(middle.y), button: 'left', clickCount: 1 });
        win.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(middle.x), y: Math.round(middle.y), button: 'left', clickCount: 1 });
        await delay(150); assert.equal(await js('genesis.snapshot().tiles[64*192+96]'), 3); checks.push('Terrain painting works on blank world');
        await click('[data-tool="snow"]');
        for (const type of ['mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, x: Math.round(middle.x), y: Math.round(middle.y), button: 'left', clickCount: 1 });
        await delay(80);
        assert.equal(await js('genesis.snapshot().tiles[64*192+96]'), 11);
        await click('[data-category="life"]'); await click('[data-tool="foxfolk"]');
        for (const type of ['mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, x: Math.round(middle.x), y: Math.round(middle.y), button: 'left', clickCount: 1 });
        await delay(80);
        assert.equal(await js('genesis.snapshot().people[0].race'), 'foxfolk');
        await click('[data-category="creatures"]'); await click('[data-tool="butterfly"]');
        for (const type of ['mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, x: Math.round(middle.x), y: Math.round(middle.y), button: 'left', clickCount: 1 });
        await delay(80);
        assert.equal(await js('genesis.snapshot().animals[0].species'), 'butterfly');
        checks.push('New biome, people, and wildlife brushes work through native map input');
        await click('#load'); await click('#restore');
        assert.equal(await js('genesis.snapshot().name'), 'The Emerald Isles'); assert.ok(await js('genesis.stats().population > 0')); checks.push('Load restores saved populated world');
        await click('#inspect');
        win.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(middle.x), y: Math.round(middle.y) }); await delay(100);
        assert.equal(await js('document.getElementById("world-tooltip").hidden'), false); checks.push('Inspect shows live tile details');
        await click('#pause');
        for (const kind of ['people', 'animals']) {
            const point = await js(`(()=>{const u=genesis.snapshot().${kind}[0],c=genesis.camera(),r=document.querySelector('#world').getBoundingClientRect();return{x:r.x+c.origin.x+u.x*6*c.base*c.zoom,y:r.y+c.origin.y+u.y*6*c.base*c.zoom}})()`);
            win.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(point.x), y: Math.round(point.y), button: 'left', clickCount: 1 });
            win.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(point.x), y: Math.round(point.y), button: 'left', clickCount: 1 });
            await delay(80);
            assert.equal(await js('document.getElementById("entity-card").hidden'), false);
            assert.ok(await js('document.getElementById("entity-card").textContent.includes("Health")'));
            assert.ok(await js(`document.getElementById('entity-card').textContent.includes('${kind === 'people' ? 'Weapon' : 'Nature'}')`));
            if (kind === 'people') await fs.writeFile(path.join(artifact_dir, 'creature-inspection.png'), (await win.webContents.capturePage()).toPNG());
            await click('#entity-card button');
        }
        checks.push('Native clicks inspect individual people and wildlife with live health and equipment');
        await click('#help'); assert.equal(await js('document.getElementById("help-dialog").open'), true); await click('#help-dialog [data-close]');
        checks.push('Help dialog opens and closes');
        await click('#diplomacy');
        assert.equal(await js('document.getElementById("diplomacy-dialog").open'), true);
        assert.ok(await js('document.querySelectorAll("#source-kingdom option").length >= 2'));
        assert.ok(await js('document.getElementById("kingdom-profile").textContent.includes("Stone club")'));
        assert.ok(await js('document.getElementById("kingdom-profile").textContent.includes("farmers")'));
        assert.ok(await js('document.getElementById("kingdom-profile").textContent.includes("trade routes underway")'));
        checks.push('Kingdom profile shows jobs, soldiers, and trade activity');
        await click('[data-relation="war"]');
        assert.equal(await js('genesis.snapshot().relations[0].status'), 'war');
        await click('[data-relation="alliance"]');
        assert.equal(await js('genesis.snapshot().relations[0].status'), 'alliance');
        await click('#diplomacy-dialog [data-close]');
        checks.push('Kingdoms dialog changes and saves relations');
        // Verify export reaches Electron's download flow and produces a valid portable save.
        const export_path = path.join(artifact_dir, 'exported-world.json');
        const downloaded = new Promise((resolve, reject) => {
            const timer = setTimeout(() => reject(new Error('Export did not download')), 5000);
            win.webContents.session.once('will-download', (_event, item) => {
                item.setSavePath(export_path);
                item.once('done', (_event, state) => { clearTimeout(timer); state === 'completed' ? resolve() : reject(new Error(state)); });
            });
        });
        await click('#load'); await click('#export'); await downloaded;
        const exported = JSON.parse(await fs.readFile(export_path, 'utf8')); assert.equal(exported.format, 'genesis-grove'); checks.push('Export writes a portable world JSON file');
        await js(`(()=>{const input=document.getElementById('import'),dt=new DataTransfer();dt.items.add(new File([JSON.stringify({format:'wrong'})],'corrupt.json',{type:'application/json'}));input.files=dt.files;input.dispatchEvent(new Event('change'))})()`);
        await delay(100);
        assert.equal(await js('genesis.snapshot().name'), 'The Emerald Isles');
        assert.ok(await js('document.getElementById("toast").textContent.includes("not a valid")')); checks.push('Invalid import preserves current world');
        const imported = { ...exported, name: 'Imported Adventure' };
        imported.villages.forEach(kingdom => { kingdom.tech_points = 100; kingdom.research_level = 4; });
        imported.people.forEach(person => { person.weapon_level = 4; person.armor_level = 4; });
        await js(`(()=>{const input=document.getElementById('import'),dt=new DataTransfer();dt.items.add(new File([${JSON.stringify(JSON.stringify(imported))}],'world.json',{type:'application/json'}));input.files=dt.files;input.dispatchEvent(new Event('change'))})()`);
        await delay(150);
        assert.equal(await js('genesis.snapshot().name'), 'Imported Adventure'); checks.push('Valid world file imports through the file-input handler');
        assert.equal(await js('document.getElementById("age-label").textContent'), 'STEEL AGE');
        await click('#diplomacy');
        assert.ok(await js('document.getElementById("kingdom-profile").textContent.includes("Steel sword")'));
        await click('#diplomacy-dialog [data-close]');
        await fs.writeFile(path.join(artifact_dir, 'world-steel-age.png'), (await win.webContents.capturePage()).toPNG());
        checks.push('Imported technology updates the age display and kingdom equipment');
        await click('#new-world');
        await js(`document.querySelector('#new-form [name=preset]').value='wildlands';document.querySelector('#new-form [name=seed]').value='color-world';document.querySelector('#new-form').requestSubmit()`);
        await click('#menu-paint');
        assert.equal(await js('genesis.snapshot().villages.length'), 8);
        assert.equal(await js('new Set(genesis.snapshot().villages.map(v=>v.race)).size'), 8);
        assert.ok(await js('genesis.snapshot().tiles.includes(15)'));
        await fs.writeFile(path.join(artifact_dir, 'world-wildlands.png'), (await win.webContents.capturePage()).toPNG());
        checks.push('Prismatic Wildlands starts eight peoples on a colorful generated map');
        await click('#new-world');
        await js(`(()=>{const scenario=document.getElementById('scenario');scenario.value='hundred';scenario.dispatchEvent(new Event('change'));document.querySelector('#new-form').requestSubmit()})()`);
        await click('#menu-start');
        assert.equal(await js('genesis.snapshot().villages.length'), 100);
        assert.equal(await js('genesis.snapshot().laws.rebellions'), false);
        assert.equal(await js('document.getElementById("survival").hidden'), false);
        checks.push('100-kingdom challenge creates founders and survival display');
        await click('#diplomacy');
        assert.equal(await js('document.getElementById("law-expansion").checked'), true);
        assert.ok(await js('document.getElementById("kingdom-profile").textContent.includes("towns")'));
        checks.push('Challenge exposes expansion law and kingdom profile');
        await click('#law-rebellions');
        assert.equal(await js('genesis.snapshot().laws.rebellions'), true);
        await click('#diplomacy-dialog [data-close]');
        checks.push('World-law toggle updates the simulation');
        await click('[data-speed="20"]');
        assert.equal(await js(`document.querySelector('[data-speed="20"]').classList.contains('active')`), true);
        await fs.writeFile(path.join(artifact_dir, 'world-challenge.png'), (await win.webContents.capturePage()).toPNG());
        checks.push('20× challenge speed and screenshot render');
        await win.setSize(900, 680); await delay(200);
        assert.equal(await js('document.documentElement.scrollWidth <= window.innerWidth'), true); checks.push('Compact layout fits a smaller window');
        assert.equal(await js('getComputedStyle(document.querySelector(".info-panel")).display'), 'none');
        assert.equal(await js(`(()=>{const tabs=[...document.querySelectorAll('.tabs button')].map(e=>e.getBoundingClientRect());return tabs[0].right<=tabs[1].left&&tabs[0].bottom<=tabs[2].top})()`), true);
        await fs.writeFile(path.join(artifact_dir, 'world-compact.png'), (await win.webContents.capturePage()).toPNG());
        assert.deepEqual(errors, []); checks.push('No renderer errors');
        await fs.writeFile(path.join(artifact_dir, 'smoke-results.json'), JSON.stringify({ checks, errors }, null, 2));
        console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
        win.destroy(); app.quit();
    } catch (error) { console.error(error); console.error({ errors, checks }); win.destroy(); app.exit(1); }
});
